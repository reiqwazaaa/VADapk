    var code: String = "en"
        private set

    private val cache = HashMap<String, Map<String, String>>()

    fun init(ctx: Context) {
        val saved = ctx.getSharedPreferences("vad", Context.MODE_PRIVATE).getString("lang", null)
        code = if (saved != null && languages.any { it.code == saved }) saved else detect()
    }

    fun set(ctx: Context, newCode: String) {
        code = newCode
        ctx.getSharedPreferences("vad", Context.MODE_PRIVATE).edit().putString("lang", newCode).apply()
    }

    private fun detect(): String {
        var l = Locale.getDefault().language
        if (l == "in") l = "id"
        return if (languages.any { it.code == l }) l else "en"
    }

    val isRtl: Boolean get() = languages.firstOrNull { it.code == code }?.rtl == true

    fun t(key: String): String = table(code)[key] ?: table("en")[key] ?: key

    fun f(key: String, vararg args: Any?): String = String.format(Locale.US, t(key), *args)

    private fun table(c: String): Map<String, String> = cache.getOrPut(c) {
        when (c) {
            "ru" -> ru()
            "zh" -> zh()
            "hi" -> hi()
            "es" -> es()
            "ar" -> ar()
            "fr" -> fr()
            "bn" -> bn()
            "pt" -> pt()
            "ur" -> ur()
            "id" -> idn()
            "de" -> de()
            "ja" -> ja()
            "tr" -> tr()
            "ko" -> ko()
            else -> en()
        }
    }

